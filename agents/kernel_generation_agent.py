_KERNELS_DIR = _REPO_ROOT / "kernels" / "generated"


# ---------------------------------------------------------------------------
# Generated kernel dataclass
# ---------------------------------------------------------------------------

@dataclass
class GeneratedKernel:
    """A GPU kernel generated by the Kernel Generation Agent."""
    session_id: str
    kernel_name: str
    target_op: str                  # attention | gemm | moe | rmsnorm | rope
    gpu_type: str
    model_id: str

    # Source code
    triton_code: str = ""           # Full Triton Python file contents
    cuda_code: str = ""             # CUDA C++ if applicable (empty for Triton-only)

    # File paths
    file_path: str = ""             # Path to the .py file
    cuda_file_path: str = ""        # Path to .cu file if generated

    # Metadata
    tile_config: Dict[str, int] = field(default_factory=dict)
    expected_speedup_pct: float = 0.0
    algorithm: str = ""             # "flash_attention_v2_causal_gqa" etc.

    # Generation status
    success: bool = False
    error: str = ""

    # Whether this kernel is a replacement for an existing vLLM kernel
    replaces_vllm_kernel: bool = False
    vllm_integration_notes: str = ""

    def load_code(self) -> str:
        """Read kernel code from file (in case it was modified after generation)."""
        if self.file_path and Path(self.file_path).exists():
            return Path(self.file_path).read_text()
        return self.triton_code


