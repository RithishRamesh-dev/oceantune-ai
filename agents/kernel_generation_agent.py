def _strip_code_fences(text: str) -> str:
    """Remove ```python ... ``` or ``` ... ``` fences from LLM output."""
    # Strip markdown fences
    text = re.sub(r"^```(?:python|cuda|cpp)?\s*\n", "", text, flags=re.MULTILINE)
    text = re.sub(r"\n```\s*$", "", text, flags=re.MULTILINE)
    # Remove any leading "Here is the kernel:" type text before the first import
    match = re.search(r"^#\s*kernels/", text, re.MULTILINE)
    if match:
        text = text[match.start():]
    elif "import triton" in text:
        idx = text.index("import triton")
        # Keep any top-level comments before it
        comment_start = text.rfind("#", 0, idx)
        if comment_start >= 0 and "\n" not in text[comment_start:idx]:
            text = text[comment_start:]
        else:
            text = text[idx:]
    return text.strip()
