"""
agents/kernel_generation_agent.py
-----------------------------------
Kernel Generation Agent — Stage 4, Part 2.

Given a KernelResearchReport and BottleneckAnalysis, generates a complete,
hardware-optimised Triton (or CUDA C++) kernel targeting the identified bottleneck.

The generated kernel is saved to kernels/generated/<session_id>/<kernel_name>.py
and can be loaded by vLLM via monkey-patch or standalone microbenchmark.

Architecture-specific optimisations the LLM is instructed to use:

NVIDIA H100/A100:
  - TMA (Tensor Memory Accelerator) for async tile loading (H100 only)
  - cp.async for double-buffered GMEM→SMEM pipeline
  - Warp specialization: producer/consumer warp groups
  - wmma / mma.sync for Tensor Core instructions
  - Register tiling: careful BLOCK_M/BLOCK_N/BLOCK_K selection
  - Split-K for batch-size=1 decode (small-M GEMM)

AMD MI300X:
  - Direct-to-LDS (DL) load paths
  - MFMA instruction selection (f16, bf16, fp8)
  - Wavefront-level tiling
  - LDS padding to avoid bank conflicts (stride 128 bytes)
  - ROCm Triton backend specifics (triton-rocm)

For attention kernels:
  - Online softmax (Dao/FlashAttention algorithm)
  - Causal/non-causal mask fusion
  - GQA: head group interleaving
  - Paged KV cache: block pointer arithmetic
  - Prefill vs decode kernel split

Usage
-----
    generator = KernelGenerationAgent(do_client=client)
    kernel = await generator.generate(
        research=kernel_research_report,
        bottleneck=bottleneck_analysis,
        model_id="Qwen/Qwen2.5-7B-Instruct",
        gpu_type="H100",
        session_id="...",
    )
    print(kernel.file_path)   # path to generated .py file
    print(kernel.triton_code) # full Triton kernel code
"""

