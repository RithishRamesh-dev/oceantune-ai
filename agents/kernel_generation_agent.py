class KernelGenerationAgent:
    """
    Generates hardware-optimized GPU kernels based on research findings.
    """

    def __init__(self, do_client: DOClient) -> None:
        self._client = do_client

    async def generate(
        self,
        *,
        research: KernelResearchReport,
        bottleneck: BottleneckAnalysis,
        model_id: str,
        gpu_type: str,
        session_id: str,
        model_meta: Optional[Dict[str, Any]] = None,
        generate_cuda: bool = False,
    ) -> GeneratedKernel:
        """
        Generate an optimized kernel for the bottleneck operation.

        Parameters
        ----------
        research : KernelResearchReport
            Research findings from KernelResearchAgent.
        bottleneck : BottleneckAnalysis
            The classified bottleneck.
        model_id : str
        gpu_type : str
        session_id : str
        model_meta : dict
            Model architecture (num_heads, head_dim, etc.)
        generate_cuda : bool
            Also generate CUDA C++ alongside Triton (for comparison/fallback).

        Returns
        -------
        GeneratedKernel with file_path pointing to the written kernel.
        """
        target_op = bottleneck.primary_component or research.target_kernel or "attention"
        kernel_name = f"oceantune_{target_op}_{gpu_type.lower().replace('-', '_')}"

        kernel = GeneratedKernel(
            session_id=session_id,
            kernel_name=kernel_name,
            target_op=target_op,
            gpu_type=gpu_type,
            model_id=model_id,
        )

        if research.top_approach:
            kernel.expected_speedup_pct = research.top_approach.expected_speedup_pct
            kernel.tile_config = research.top_approach.tile_config
            kernel.algorithm = research.top_approach.title

        log.info(
            "KernelGenerationAgent: generating %s kernel for %s on %s",
            target_op, model_id, gpu_type,
        )

        user_msg = self._build_generation_prompt(
            research=research,
            bottleneck=bottleneck,
            kernel_name=kernel_name,
            target_op=target_op,
            model_id=model_id,
            gpu_type=gpu_type,
            model_meta=model_meta or {},
        )

        try:
            # Generate Triton kernel
            triton_code = await self._client.chat(
                messages=[{"role": "user", "content": user_msg}],
                system=_TRITON_GENERATION_SYSTEM_PROMPT,
                json_mode=False,  # Plain code output
            )

            # Strip any markdown fences
            triton_code = _strip_code_fences(triton_code)
            kernel.triton_code = triton_code

            # Write to disk
            kernel_dir = _KERNELS_DIR / session_id
            kernel_dir.mkdir(parents=True, exist_ok=True)
            kernel_path = kernel_dir / f"{kernel_name}.py"
            kernel_path.write_text(triton_code, encoding="utf-8")
            kernel.file_path = str(kernel_path)
            kernel.success = True

            log.info("KernelGenerationAgent: wrote %d lines to %s",
                     len(triton_code.splitlines()), kernel_path)

            # Optionally generate CUDA C++ as well
            if generate_cuda:
                cuda_code = await self._generate_cuda(
                    research=research,
                    bottleneck=bottleneck,
                    kernel_name=kernel_name,
                    model_id=model_id,
                    gpu_type=gpu_type,
                    model_meta=model_meta or {},
                )
                if cuda_code:
                    cuda_path = kernel_dir / f"{kernel_name}.cu"
                    cuda_path.write_text(cuda_code, encoding="utf-8")
                    kernel.cuda_code = cuda_code
                    kernel.cuda_file_path = str(cuda_path)

        except (DOClientError, Exception) as exc:
            log.warning("KernelGenerationAgent LLM call failed: %s", exc)
            kernel.error = str(exc)
            # Write a skeleton kernel as fallback
            kernel.triton_code = self._generate_skeleton(target_op, gpu_type, model_meta or {})
            kernel_dir = _KERNELS_DIR / session_id
            kernel_dir.mkdir(parents=True, exist_ok=True)
            kernel_path = kernel_dir / f"{kernel_name}_skeleton.py"
            kernel_path.write_text(kernel.triton_code, encoding="utf-8")
            kernel.file_path = str(kernel_path)
            kernel.success = False

        return kernel

    def _build_generation_prompt(
        self,
        *,
        research: KernelResearchReport,
        bottleneck: BottleneckAnalysis,
        kernel_name: str,
        target_op: str,
        model_id: str,
        gpu_type: str,
        model_meta: Dict[str, Any],
    ) -> str:
        vendor = "amd" if gpu_type in {"MI300X", "MI325X", "MI350X"} else "nvidia"
        top = research.top_approach

        sections = [
            f"# Kernel to generate: {kernel_name}",
            f"# Target operation: {target_op}",
            f"# Model: {model_id}",
            f"# GPU: {gpu_type} (vendor={vendor})",
            "",
            "## Research findings",
        ]

        if top:
            sections.extend([
                f"Algorithm: {top.title}",
                f"Approach type: {top.approach_type}",
                f"Expected speedup: {top.expected_speedup_pct:.0f}%",
                f"Evidence: {top.evidence}",
                f"Algorithm description: {top.triton_approach or '(use standard algorithm)'}",
                f"Tile config: {json.dumps(top.tile_config) if top.tile_config else 'autotuned'}",
            ])
            if vendor == "nvidia":
                sections.append(f"NVIDIA notes: {top.nvidia_notes or 'standard CUDA/Triton'}")
            else:
                sections.append(f"AMD notes: {top.amd_notes or 'standard ROCm Triton'}")

        sections.append("")
        sections.append("## Bottleneck context")
        sections.append(f"Primary bottleneck class: {bottleneck.primary_bottleneck}")
        sections.append(f"Roofline bound: {bottleneck.roofline_bound}")
        sections.append(f"Arithmetic intensity: {bottleneck.arithmetic_intensity:.1f} FLOP/byte")

        if model_meta:
            sections.append("")
            sections.append("## Model architecture")
            sections.append(json.dumps(model_meta, indent=2))

        sections.append("")
        sections.append(f"## Diagnostic questions from bottleneck analyst")
        for q in bottleneck.diagnostic_questions[:3]:
            sections.append(f"  - {q}")

        sections.append("")
        sections.append("Generate the complete Triton kernel file for this operation.")

        return "\n".join(sections)

    async def _generate_cuda(
        self,
        *,
        research: KernelResearchReport,
        bottleneck: BottleneckAnalysis,
        kernel_name: str,
        model_id: str,
        gpu_type: str,
        model_meta: Dict[str, Any],
    ) -> str:
        """Optionally generate a CUDA C++ companion kernel."""
        user_msg = (
            f"Generate a CUDA C++ kernel implementing: {research.generation_priority}\n"
            f"Kernel name: {kernel_name}\n"
            f"GPU: {gpu_type}\n"
            f"Model: {model_id}\n"
            f"Architecture: {json.dumps(model_meta, indent=2)}\n"
            f"Use wmma/mma.sync for Tensor Cores, cp.async for async GMEM→SMEM."
        )
        try:
            code = await self._client.chat(
                messages=[{"role": "user", "content": user_msg}],
                system=_CUDA_GENERATION_SYSTEM_PROMPT,
                json_mode=False,
            )
            return _strip_code_fences(code)
        except Exception as exc:
            log.warning("CUDA generation failed: %s", exc)
            return ""

